from fpdf import FPDF
import pandas as pd
import io
import datetime

class PDFReportGenerator(FPDF):
    def header(self):
        # Professional Header with Blue Accent
        self.set_fill_color(0, 51, 102) # Deep Blue
        self.rect(0, 0, 210, 30, 'F')
        
        self.set_y(10)
        self.set_font('Helvetica', 'B', 16)
        self.set_text_color(255, 255, 255)
        self.cell(0, 10, 'TabuLLM: AI Benchmark Report', border=0, ln=1, align='C')
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(128, 128, 128)
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        self.cell(0, 10, f'Generated by TabuLLM AI Pipeline | {timestamp} | Page {self.page_no()}', 0, 0, 'C')

    def section_header(self, title, color=(0, 102, 204)):
        self.ln(8)
        self.set_font('Helvetica', 'B', 14)
        self.set_text_color(*color)
        self.cell(0, 10, title, ln=1)
        self.set_draw_color(*color)
        self.line(self.get_x(), self.get_y(), self.get_x() + 190, self.get_y())
        self.ln(4)

    def executive_summary(self, avg_fidelity, global_metrics):
        self.add_page()
        self.section_header("1. Executive Summary: Consolidated Audit Results")
        self.set_font('Helvetica', '', 11)
        self.set_text_color(50, 50, 50)
        self.multi_cell(0, 7, "This report consolidates the results of the TabuLLM data augmentation pipeline. "
                            "The objective is to audit the fidelity, diversity, and privacy of the synthetic data generated via LLM inference. "
                            "Below are the averaged performance indicators across all processed datasets in this session.")
        self.ln(5)
        
        if global_metrics:
            g_table = [[k, str(v)] for k, v in global_metrics.items()]
            self.draw_table(["Audit Indicator", "Global Session Mean (± Std)"], g_table, [110, 80], font_size=9, header_color=(200, 220, 240))
        else:
            self.draw_table(["Metric", "Consolidated Value"], [["Avg Fidelity", str(avg_fidelity)]], [80, 110])
        self.ln(5)

    def get_delta_color(self, metric_name, delta_val_str):
        """
        Determines the RGB color for a delta string based on metric type and value.
        Better = Green (220, 255, 220)
        Slightly Worse = Orange (255, 245, 230)
        Worse = Red (255, 235, 235)
        """
        try:
            # Extract numeric value including percentage support
            val = float(delta_val_str.replace('%', '').replace('+', '').strip())
            m_lower = metric_name.lower()
            
            # Identify if "Lower is Better"
            lower_is_better = any(x in m_lower for x in ["rmse", "mse", "mae", "drift", "risk", "memorization", "shift"])
            
            if lower_is_better:
                if val <= 0: return (220, 255, 220) # Green (Better or Equal)
                if val <= 5.0: return (255, 245, 230) # Orange (Slightly Worse)
                return (255, 235, 235) # Red (Worse)
            else:
                # Higher is Better
                if val >= 0: return (220, 255, 220) # Green (Better or Equal)
                if val >= -5.0: return (255, 245, 230) # Orange (Slightly Worse)
                return (255, 235, 235) # Red (Worse)
        except:
            return (255, 255, 255) # Default White

    def draw_table(self, header, data, col_widths, font_size=8, header_color=(230, 230, 250), row_colors=None, cell_colors=None):
        # Header
        self.set_font("helvetica", 'B', font_size + 1)
        self.set_fill_color(*header_color)
        for h, width in zip(header, col_widths):
            self.cell(width, 7, str(h), border=1, fill=True, align='C')
        self.ln()
        
        self.set_font('Helvetica', '', font_size)
        for i, row in enumerate(data):
            if self.get_y() > 270: self.add_page()
            
            # Determine base row color
            base_row_color = (255, 255, 255)
            if row_colors and i < len(row_colors):
                base_row_color = row_colors[i]
                
            # Multi-line cell support for long content
            max_lines = 1
            for val, width in zip(row, col_widths):
                lines = len(self.multi_cell(width, 5, str(val), split_only=True))
                max_lines = max(max_lines, lines)
            
            row_height = max_lines * 5
            x_start = self.get_x()
            y_start = self.get_y()
            
            for j, (val, width) in enumerate(zip(row, col_widths)):
                # Check for cell-specific color, otherwise use row/base color
                if cell_colors and (i, j) in cell_colors:
                    self.set_fill_color(*cell_colors[(i, j)])
                else:
                    self.set_fill_color(*base_row_color)
                    
                self.multi_cell(width, 5, str(val), border=1, align='L', fill=True)
                self.set_xy(x_start + width, y_start)
                x_start += width
            self.ln(row_height)

    def draw_footnotes(self, footnotes):
        if not footnotes: return
        self.set_y(-40)
        self.set_font('Helvetica', 'I', 7)
        self.set_text_color(100, 100, 100)
        self.line(10, self.get_y(), 200, self.get_y())
        for i, text in enumerate(footnotes, 1):
            self.cell(0, 4, f"[{i}] {text}", ln=1)

def generate_benchmark_pdf(report_data):
    pdf = PDFReportGenerator()
    
    summary = report_data.get("executive_summary", {})
    pdf.executive_summary(summary.get("avg_fidelity", "N/A"), summary.get("global_metrics", {}))

    for d_id, d_info in report_data.get("datasets", {}).items():
        pdf.add_page()
        pdf.section_header(f"Dataset Audit: {d_info.get('filename')}")
        
        # 1. Dataset Portrait
        pdf.set_font('Helvetica', 'B', 12)
        pdf.cell(0, 10, "1. Dataset Portrait", ln=1)
        meta = d_info.get("metadata", {})
        meta_table = [[k, str(v)] for k, v in meta.items()]
        pdf.draw_table(["Attribute", "Value"], meta_table, [60, 130], font_size=9)
        pdf.ln(5)

        # 2. Generation Strategy (with Footnote)
        pdf.set_font('Helvetica', 'B', 12)
        pdf.cell(0, 10, "2. Generation Strategy & LLM Config [1]", ln=1)
        params = d_info.get("params", {}).get("generation", {})
        param_table = []
        for i, (k, v) in enumerate(params.items(), 12): # Start at 12 as quality metrics are 1-11
             param_table.append([f"{k} (*{i})", str(v)])
        pdf.draw_table(["Parameter", "Configuration"], param_table, [80, 110], font_size=9)
        
        # 3. Statistical Significance
        pdf.set_font('Helvetica', 'B', 12)
        pdf.cell(0, 10, "3. Statistical Significance & Data Drift", ln=1)
        inf_table = d_info.get("inference_table", [])
        if inf_table:
            pdf.draw_table(["Feature", "Orig Mean", "Aug Mean", "Shift", "P-Value", "Status"], 
                           inf_table, [50, 30, 30, 25, 30, 25], font_size=8,
                           cell_colors={(i, 3): pdf.get_delta_color("Shift", inf_table[i][3]) for i in range(len(inf_table))})
        pdf.ln(5)

        # 4. Quality & Fidelity (with Footnotes)
        pdf.set_font('Helvetica', 'B', 12)
        pdf.cell(0, 10, "4. Quality & Fidelity Metrics (Mean ± Std)", ln=1)
        
        metric_desc = [
            "Synthetic Fidelity (JSD): Overall distribution similarity.",
            "Correlation Stability: Multivariate relationships preserved.",
            "Distribution Consistency: Median feature similarity.",
            "Entropy Preservation: Information diversity maintained.",
            "Mean Z Score Drift: Standardized distribution shift.",
            "Categorical Fidelity: Category distribution similarity.",
            "Privacy Risk: Synthetic rows too close to originals.",
            "Data Density: Non-missing cells in augmented data.",
            "Coverage Score: Synthetic coverage of original space.",
            "Feature Accuracy: Mean feature similarity.",
            "Novelty Score: Distance ratio to nearest neighbors."
        ]
        
        metrics = d_info.get("metrics", {})
        metric_table = []
        for i, (k, v) in enumerate(metrics.items(), 1):
            metric_table.append([f"{k} (*{i})", str(v)])
            
        pdf.draw_table(["Metric Category", "Aggregated Score"], metric_table, [120, 70], font_size=9)
        
        # Draw Footnotes for this page
        p_keys = list(params.keys())
        p_desc = [f"(*{12+i}) {k}: Contextual constraint or model parameter." for i, k in enumerate(p_keys)]
        pdf.draw_footnotes(p_desc + metric_desc)

        # 5. Visual Data Audit (Geometric & Correlation Analysis)
        plots = d_info.get("plots", [])
        if plots:
            pdf.add_page()
            pdf.section_header("5. Visual Data Audit: Distribution & Relationship Evidence")
            
            # Group correlations for side-by-side
            corrs = [p for p in plots if "Relational" in p['title']]
            others = [p for p in plots if "Relational" not in p['title']]
            
            if len(corrs) == 2:
                # Render side-by-side
                pdf.set_font('Helvetica', 'B', 10)
                pdf.set_text_color(0, 51, 102)
                pdf.cell(90, 8, corrs[0]['title'], ln=0)
                pdf.cell(90, 8, corrs[1]['title'], ln=1)
                y_start = pdf.get_y()
                pdf.image(corrs[0]['path'], x=10, y=y_start, w=90)
                pdf.image(corrs[1]['path'], x=110, y=y_start, w=90)
                pdf.set_y(y_start + 70) # Skip fixed height
                pdf.ln(5)
            else:
                for plot in corrs:
                    pdf.set_font('Helvetica', 'B', 11)
                    pdf.cell(0, 10, f"Analysis: {plot['title']}", ln=1)
                    pdf.image(plot['path'], x=15, w=180)
                    pdf.ln(5)
            
            # Render PCA or others
            for plot in others:
                pdf.set_font('Helvetica', 'B', 11)
                pdf.set_text_color(0, 51, 102)
                pdf.cell(0, 10, f"Analysis: {plot['title']}", ln=1)
                try:
                    pdf.image(plot['path'], x=15, w=180)
                    pdf.ln(5)
                except: pass

        # 6. Downstream ML Utility (SUBDIVIDED BY MODEL)
        pdf.add_page()
        pdf.section_header("6. Downstream ML Utility: Comparative Analysis")
        ml_res = d_info.get("ml_results", {})
        if ml_res:
            for m_type, m_perf in ml_res.items():
                pdf.set_font('Helvetica', 'B', 11)
                pdf.set_text_color(0, 51, 102)
                pdf.cell(0, 10, f"Model: {m_type.replace('_', ' ').upper()}", ln=1)
                
                rows = []
                for metric_name, vals in m_perf.items():
                    if metric_name == "folds_metadata": continue
                    
                    # Safe extraction supporting old and new schemas
                    if isinstance(vals, dict):
                        m_real = vals.get("real") or vals.get("orig_m") or "N/A"
                        m_aug = vals.get("aug") or vals.get("aug_m") or "N/A"
                        m_delta = vals.get("delta") or vals.get("d_m") or "0"
                        rows.append([metric_name.upper(), str(m_real), str(m_aug), str(m_delta)])
                    else:
                        # Fallback for simple string metrics
                        rows.append([metric_name.upper(), "N/A", str(vals), "N/A"])
                
                pdf.draw_table(["Metric", "Real (Baseline)", "Augmented", "Delta (Lift)"], 
                               rows, [50, 45, 45, 50], font_size=9, header_color=(200, 220, 240),
                               cell_colors={(i, 3): pdf.get_delta_color(rows[i][0], rows[i][3]) for i in range(len(rows))})
                pdf.ln(5)
        else:
            pdf.cell(0, 10, "No ML evaluation results found.", ln=1)

        # F. Appendix: BENCHMARK DATA TRACE
        pdf.add_page()
        pdf.section_header("Appendix: Benchmark Data Trace")
        
        # Legend
        pdf.set_font('Helvetica', 'I', 8)
        pdf.set_text_color(100, 100, 100)
        pdf.cell(0, 5, "Legend: [Light Blue] = Original Context Rows | [Light Green] = Generated Synthetic Rows", ln=1)
        pdf.ln(2)
        
        # 1. Original Dataset (Full)
        pdf.set_font('Helvetica', 'B', 11)
        pdf.set_text_color(0, 51, 102)
        pdf.cell(0, 10, "A. Baseline: Original Dataset (Full Record Sample)", ln=1)
        orig_df = d_info.get("samples", {}).get("orig")
        if orig_df is not None and not orig_df.empty:
            raw_cols = list(orig_df.columns[:10])
            headers = ["#"] + raw_cols
            rows = [[i+1] + r for i, r in enumerate(orig_df[raw_cols].values.tolist())]
            pdf.draw_table(headers, rows, [10] + [180/len(raw_cols)]*len(raw_cols), font_size=5)
        pdf.ln(10)

        # 2. Synthetic Folds (Full)
        for i, fold in enumerate(d_info.get("appendix", []), 1):
            if pdf.get_y() > 180: pdf.add_page()
            else: pdf.ln(10)
            
            ctx_str = f" | Context Ratio: {fold.get('ctx_ratio')}%" if fold.get('ctx_ratio') else ""
            
            pdf.set_font('Helvetica', 'B', 10)
            pdf.set_text_color(0, 51, 102)
            pdf.cell(0, 8, f"B.{i} Audit Trace: {fold['name']}{ctx_str}", ln=1)
            
            f_df = fold['sample']
            f_colors = fold.get('row_colors', [])
            if not f_df.empty:
                raw_cols = list(f_df.columns[:10])
                headers = ["#"] + raw_cols
                display_rows = f_df[raw_cols].values.tolist()
                rows = [[i+1] + r for i, r in enumerate(display_rows)]
                pdf.draw_table(headers, rows, [10] + [180/len(raw_cols)]*len(raw_cols),
                               font_size=5, row_colors=f_colors)

    return pdf.output(dest='S')
