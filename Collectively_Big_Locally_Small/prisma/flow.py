"""Write every number of the PRISMA flow and of Section 5.5 as LaTeX macros (prisma/prisma_numbers.tex).

main.tex inputs this file, so the flow diagram (Figure 7) and the text are regenerated by running
    python3 prisma/search.py     # queries the databases (slow; results are saved)
    python3 prisma/screen.py
    python3 prisma/classify.py   # needs data/corpus_lookup.jsonl from fetch_corpus_abstracts.py
    python3 prisma/verify.py
    python3 prisma/flow.py
"""
import csv
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"


def fmt(x):
    return f"{x:,}".replace(",", "{,}")


def pct(x):
    return f"{100 * x:.0f}\\%"


def main():
    flow = json.load(open(DATA / "flow_search.json"))
    cls = json.load(open(DATA / "classify_summary.json"))
    ver = json.load(open(DATA / "verify_summary.json"))
    log = json.load(open(DATA / "search_log.json"))
    bg = Counter(r["reason"] for r in csv.DictReader(open(DATA / "excluded_background.csv")))
    ident = flow["identified"]
    auto = sum(flow["automation_excluded"].values())
    screened = flow["screened"] - auto
    excluded = sum(flow["excluded"].values())
    n = {
        "SearchDate": "8 October 2026",
        "IdentPubMed": fmt(ident.get("PubMed", 0)),
        "IdentMedRxiv": fmt(ident.get("medRxiv", 0)),
        "IdentArXiv": fmt(ident.get("arXiv", 0)),
        "IdentArXivEPMC": fmt(ident.get("arXiv (Europe PMC)", 0)),
        "IdentTotal": fmt(flow["identified_total"]),
        "Duplicates": fmt(flow["duplicates"]),
        "AutoNoAbstract": fmt(flow["automation_excluded"]["A1"]),
        "AutoType": fmt(flow["automation_excluded"]["A2"]),
        "Screened": fmt(screened),
        "ExclTotal": fmt(excluded),
        "ExclSetting": fmt(flow["excluded"]["R1"]),
        "ExclLimitation": fmt(flow["excluded"]["R2"]),
        "ExclTrial": fmt(flow["excluded"]["R3"]),
        "ExclGuideline": fmt(flow["excluded"]["R4"]),
        "ExclNoLearning": fmt(flow["excluded"]["R5"]),
        "Eligible": fmt(flow["eligible"]),
        "Since": fmt(sum(v for y, v in cls["field_years"].items() if int(y) >= 2023)),
        "VerifyN": str(ver["n"]),
        "VerifyPrecision": pct(ver["precision"]),
        "VerifyNPV": pct(ver["npv"]),
        "VerifySens": pct(ver["sensitivity_in_sample"]),
        "CorpusInScope": str(cls["recall"]["corpus_in_scope"]),
        "CorpusIndexed": str(cls["recall"]["indexed_in_searched_sources"]),
        "CorpusRetrieved": str(cls["recall"]["retrieved_of_indexed"]),
        "Recall": pct(cls["recall"]["recall_of_indexed"]),
        "CoderN": str(cls["coder_validation"]["n"]),
        "CoderAgree": pct(cls["coder_validation"]["primary_agreement"]),
        "CoderKappa": f"{cls['coder_validation']['primary_kappa']:.2f}",
        "CoderClassRecall": pct(cls["coder_validation"]["class_recall"]),
        "CellRho": f"{cls['cell_spearman']:.2f}",
        "GapsConfirmed": str(cls["gaps_in_bottom_third"]),
        "GapsTotal": str(len(cls["gaps"])),
        "BibTotal": "329",
        "BgTotal": str(sum(bg.values())),
        "BgXOne": str(bg["X1"]),
        "BgXTwo": str(bg["X2"]),
        "BgXThree": str(bg["X3"]),
        "Coded": "290",
    }
    prim = cls["field_primary_channel"]
    tot = cls["eligible"]
    for ch in ["P1", "P2", "P3", "P4", "P5", "P6"]:
        n[f"Field{'ABCDEF'[int(ch[1]) - 1]}"] = pct(prim[ch] / tot)
    n["FieldNone"] = pct(prim["none"] / tot)
    lines = ["% Generated by prisma/flow.py from prisma/data/*.json. Do not edit."]
    lines += [f"\\newcommand{{\\Prisma{k}}}{{{v}}}" for k, v in n.items()]
    (HERE / "prisma_numbers.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
